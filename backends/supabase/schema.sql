-- =====================================================================
-- Mathematics Advanced — Subject Cloud
-- Shared backend for Supabase (PostgreSQL)
-- =====================================================================
-- Run this once in your Supabase project:  Dashboard → SQL Editor → New
-- query → paste this whole file → Run.
--
-- What it gives the static GitHub Pages site:
--   * shared student registration (username + password issued here, so two
--     students with the same first name never collide),
--   * shared visitor counter and per-day/per-file download counters,
--   * an admin-only export used by the dashboard and by the GitHub Action
--     that mirrors the register into data/cloud-data.json in the repository.
--
-- Security model
--   * Every table has Row Level Security enabled and NO policies, and direct
--     table privileges are revoked from the anon/authenticated roles. That
--     means the publishable key in the web page can read and write nothing on
--     its own.
--   * Everything the page is allowed to do goes through the SECURITY DEFINER
--     functions below, which validate their input, log events and increment
--     counters. Think of them as the API of this backend.
--   * Never put a secret key (sb_secret_… / service_role) in the web page or
--     in the repository. The publishable key (sb_publishable_… / legacy anon
--     JWT) is designed to be public.
-- =====================================================================

-- No extension is required: gen_random_uuid() is built into PostgreSQL 13+
-- (Supabase runs 15+), which keeps this script portable to any Postgres host.

