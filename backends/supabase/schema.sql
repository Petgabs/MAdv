create or replace function public.madv_config_bool(p_key text, p_default boolean)
returns boolean
language sql
stable
set search_path = public, pg_temp
as $$
  select coalesce(
    nullif((select value from public.madv_config where key = p_key), '')::boolean,
    p_default);
$$;

create or replace function public.madv_config_int(p_key text, p_default bigint)
returns bigint
language sql
stable
set search_path = public, pg_temp
as $$
  select coalesce(
    nullif((select value from public.madv_config where key = p_key), '')::bigint,
    p_default);
$$;

-- "Year 11" -> "11", used for the deterministic student password.
create or replace function public.madv_year_digits(p_year text)
returns text
language sql
immutable
set search_path = public, pg_temp
as $$
  select coalesce(regexp_replace(coalesce(p_year, ''), '[^0-9]', '', 'g'), '');
$$;

-- ------------------------------------------------------------ counters
create or replace function public.madv_bump_counter(p_key text, p_delta bigint)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_value bigint;
begin
  insert into public.madv_counters (key, value)
  values (p_key, greatest(p_delta, 0))
  on conflict (key) do update
    set value = madv_counters.value + greatest(p_delta, 0), updated_at = now()
  returning value into v_value;
  return coalesce(v_value, 0);
end;
$$;

