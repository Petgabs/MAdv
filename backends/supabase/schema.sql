-- One row per student. client_id is the id generated by the browser that
-- registered the student, so the same record can be found again offline.
create table if not exists public.madv_students (
  id             uuid primary key default gen_random_uuid(),
  client_id      text not null unique,
  first_name     text not null,
  username       text not null unique,
  password       text not null,
  year           text not null default '',
  status         text not null default 'active',
  notes          text not null default '',
  registered_at  timestamptz not null default now(),
  last_visit     timestamptz,
  visit_count    integer not null default 0,
  download_count integer not null default 0,
  updated_at     timestamptz not null default now(),
  constraint madv_students_status_check check (status in ('active', 'blocked'))
);
create index if not exists madv_students_username_idx on public.madv_students (lower(username));

-- Aggregate counters: 'visits', 'downloads'.
create table if not exists public.madv_counters (
  key        text primary key,
  value      bigint not null default 0,
  updated_at timestamptz not null default now()
);
insert into public.madv_counters (key, value) values ('visits', 0), ('downloads', 0)
on conflict (key) do nothing;

-- One row per calendar day, used for the 14-day sparkline.
create table if not exists public.madv_daily (
  day        text primary key,
  visits     bigint not null default 0,
  downloads  bigint not null default 0,
  updated_at timestamptz not null default now()
);

-- Per-file download totals (mirrored onto each resource in the library).
create table if not exists public.madv_file_totals (
  resource_key     text primary key,
  total            bigint not null default 0,
  last_download_at timestamptz
);

-- Devices seen at least once = unique visitor count.
create table if not exists public.madv_devices (
  device_id  text primary key,
  first_seen timestamptz not null default now(),
  last_seen  timestamptz not null default now(),
  visits     bigint not null default 0
);

-- Idempotency for download events (a retry must not double count).
create table if not exists public.madv_download_events (
  event_id    text primary key,
  resource_key text not null,
  created_at  timestamptz not null default now()
);

-- Activity logs (bounded, read by the admin dashboard and the repo export).
create table if not exists public.madv_downloads (
  id           bigserial primary key,
  at           timestamptz not null default now(),
  student_id   text,
  student_name text,
  student_year text,
  resource_id  text,
  resource_key text,
  title        text,
  file_name    text,
  category     text,
  topic        text,
  year         text
);
create index if not exists madv_downloads_at_idx on public.madv_downloads (at desc);

create table if not exists public.madv_visits (
  id         bigserial primary key,
  at         timestamptz not null default now(),
  day        text not null,
  device_id  text,
  student_id text,
  name       text,
  year       text
);
create index if not exists madv_visits_at_idx on public.madv_visits (at desc);

create table if not exists public.madv_logins (
  id         bigserial primary key,
  at         timestamptz not null default now(),
  student_id text,
  name       text,
  year       text,
  ok         boolean not null default false,
  kind       text
);
create index if not exists madv_logins_at_idx on public.madv_logins (at desc);

